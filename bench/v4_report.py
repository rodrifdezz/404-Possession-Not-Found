"""docs/BENCH_V4.md from outputs/v4/results/ (bench/v4.py). EXPERIMENTAL.

The adoption rule is fixed here BEFORE any result was seen, and applied mechanically:

  a candidate is adopted against a reference (V3, or V4-A for a single added feature set) if,
  on the paired per-match spellF1 (each match = mean over 2 scenarios x 2 seeds x 2 readings of
  the truth):
    1. the mean difference is > 0 over all matches AND within each provider;
    2. it wins on at least MIN_WINS of the matches;
    3. no match loses more than MAX_LOSS;
    4. false H<->A switches per 90 min grow by no more than MAX_FALSE_GROWTH (relative).
  Among adopted candidates the simplest one is preferred unless a more complex one is better by
  more than SIMPLER_MARGIN on the mean difference.
"""

import glob
import json
import os

import numpy as np

from src import config as C

from . import v4

MIN_WINS_SHARE = 0.7
MAX_LOSS = 0.03
MAX_FALSE_GROWTH = 0.20
SIMPLER_MARGIN = 0.005
ORDER = ["V3", "V4-A", "V4-B", "V4-C", "V4-D"]
SUPERSEDED = (
    "> **Note: this decision was superseded.** With the v3 decoder costs, as below, every V4 "
    "candidate failed the false-switch condition, so V3 was kept. The nested correction of "
    "[BENCH_V4_FIX.md](BENCH_V4_FIX.md) chose the decoder's `switch_cost` inside each fold from "
    "its training matches only (9, 9, 8, 9, 8). With it, V4-C passes the same rule against V3: "
    "spellF1 0.608 -> 0.667, better on 10 / 10 matches, false switches +8.6 % (+27 % on "
    "Metrica). V4-C with `switch_cost = 9`, `dead_cost = 48` is now the default model (v4) of "
    "`python -m src.make_submission`. The tables and the rule on this page are unchanged.")
COMPLEXITY = {"V3": 0, "V4-A": 1, "V4-B": 2, "V4-C": 2, "V4-D": 3}


def load_rows():
    rows, folds = [], []
    for p in sorted(glob.glob(os.path.join(v4.RES, "fold*.json"))):
        with open(p) as fh:
            z = json.load(fh)
        rows += z["rows"]
        folds.append(z)
    return rows, folds


def per_match(rows, key):
    """{candidate: {match: mean of key}}."""
    out = {}
    for r in rows:
        out.setdefault(r["candidate"], {}).setdefault(r["match"], []).append(r[key])
    return {c: {m: float(np.mean(v)) for m, v in d.items()} for c, d in out.items()}


def summed(rows, cand, keys, matches=None):
    sel = [r for r in rows if r["candidate"] == cand and (matches is None or r["match"] in matches)]
    return {k: float(np.sum([r[k] for r in sel])) for k in keys}


def false_rate(rows, cand, matches=None):
    s = summed(rows, cand, ["ha_false", "minutes"], matches)
    return 90.0 * s["ha_false"] / s["minutes"] if s["minutes"] else float("nan")


def decide(rows, spell, cand, ref, matches):
    d = np.array([spell[cand][m] - spell[ref][m] for m in matches])
    prov = {p: [i for i, m in enumerate(matches) if v4.provider(m) == p] for p in ("metrica", "dfl")}
    prov_mean = {p: float(d[ix].mean()) for p, ix in prov.items() if ix}
    wins = int(np.sum(d > 0))
    need = int(np.ceil(MIN_WINS_SHARE * len(matches)))
    fr_c, fr_r = false_rate(rows, cand, matches), false_rate(rows, ref, matches)
    growth = fr_c / fr_r - 1.0 if fr_r else 0.0
    checks = {
        "mean > 0 overall and per provider": d.mean() > 0 and all(v > 0 for v in prov_mean.values()),
        "wins >= {}/{}".format(need, len(matches)): wins >= need,
        "worst match >= -{:.2f}".format(MAX_LOSS): d.min() >= -MAX_LOSS,
        "false switches growth <= {:.0%}".format(MAX_FALSE_GROWTH): growth <= MAX_FALSE_GROWTH,
    }
    return {"mean": float(d.mean()), "prov": prov_mean, "wins": wins, "n": len(matches),
            "worst": float(d.min()), "growth": growth, "checks": checks,
            "adopted": all(checks.values())}


def write(path=None):
    path = path or os.path.join(C.ROOT, "docs", "BENCH_V4.md")
    rows, folds = load_rows()
    if not rows:
        raise SystemExit("no results in {}".format(v4.RES))
    cands = [c for c in ORDER if any(r["candidate"] == c for r in rows)]
    matches = [m for m in v4.ALL if any(r["match"] == m for r in rows)]
    spell = per_match(rows, "spell_f1")
    macro = per_match(rows, "macro_f1")
    complete = len(folds) == len(v4.FOLDS)
    L = ["# v4 ablation bench (experimental)", "",
         "Generated by `python -m bench.v4 --report` from {} of {} outer folds{}. Nothing here "
         "uses the challenge match; the submitted model (v3) and the submission file are "
         "unchanged.".format(len(folds), len(v4.FOLDS), "" if complete else " (**PARTIAL: pilot**)"),
         "", SUPERSEDED, "",
         "## Protocol", "",
         "* 10 external matches: 3 Metrica sample matches (labels derived from their events) and "
         "7 IDSSE / DFL Bundesliga matches (official per-frame flags). Downloaded locally, never "
         "committed.",
         "* 5 outer folds of 2 whole matches: {}. A model is only ever scored on matches it was "
         "not fitted on, in either layer.".format(", ".join("{" + ", ".join(f) + "}"
                                                            for f in v4.FOLDS)),
         "* Every held-out match is degraded exactly as in `bench/run.py` (short and long ball "
         "gaps x seeds 0 and 1, seeds never used for training) and scored with the official "
         "`possession_metrics.py` against both readings of the truth (`bench/targets.py`). "
         "Identical inputs for every candidate: the comparisons are paired.",
         "* Decoder unchanged: Viterbi with the v3 costs (switch {switch_cost:g}, dead "
         "{dead_cost:g}).".format(**v4.COSTS),
         "* **V3** = the stored model on DFL matches; on a Metrica match the same recipe fitted on "
         "the two other Metrica matches (as in `BENCH_MODEL_CV.md`).",
         "* **V4-A..D** = fitted on the 8 other matches (Metrica + DFL), 7 training degradations, "
         "1 frame in {} (the same number of rows as v3, from more matches). Layer 2 is fitted on "
         "out-of-sample layer-1 probabilities from {} inner groups of whole matches. "
         "V4-B adds the possession-change features to layer 2 (`bench/v4_stack.py`); V4-C adds "
         "the touch features to layer 1 (`src/touch_features.py`); V4-D both.".format(
             v4.STEP_V4, v4.INNER),
         "* Extra measures: short possessions (< {:g} s and < {:g} s) recovered at IoU >= 0.5; "
         "false H<->A switches = predicted direct changes of team with no true change towards "
         "that team within +-{:g} s, per 90 min.".format(v4.SHORT_S, v4.VSHORT_S,
                                                          v4.SWITCH_TOL / 25.0),
         "* Adoption rule fixed before the results (`bench/v4_report.py`): mean paired spellF1 "
         "difference > 0 overall and in each provider, wins on >= {:.0%} of the matches, no "
         "match worse by more than {:.2f}, false switches up by at most {:.0%}; the simplest "
         "adopted candidate wins unless a richer one is better by more than {:.3f}.".format(
             MIN_WINS_SHARE, MAX_LOSS, MAX_FALSE_GROWTH, SIMPLER_MARGIN), ""]

    # per match
    L += ["## spellF1 per held-out match", "",
          "| match | provider | " + " | ".join(cands) + " |",
          "|---|---|" + "---|" * len(cands)]
    for m in matches:
        L.append("| {} | {} | ".format(m, v4.provider(m)) +
                 " | ".join("{:.3f}".format(spell[c][m]) for c in cands) + " |")
    for p in ("metrica", "dfl"):
        ms = [m for m in matches if v4.provider(m) == p]
        if ms:
            L.append("| **mean {}** | | ".format(p) + " | ".join(
                "**{:.3f}**".format(np.mean([spell[c][m] for m in ms])) for c in cands) + " |")
    L.append("| **mean all** | | " + " | ".join(
        "**{:.3f}**".format(np.mean([spell[c][m] for m in matches])) for c in cands) + " |")

    L += ["", "## Other measures (all held-out matches)", "",
          "| | macroF1 metrica | macroF1 dfl | possessions pred / true | short < 5 s recovered "
          "| very short < 2 s recovered | false H<->A per 90 min | predicted H<->A per 90 min |",
          "|---|---|---|---|---|---|---|---|"]
    for c in cands:
        s = summed(rows, c, ["n_pred", "n_gt", "short_n", "short_hit", "vshort_n", "vshort_hit",
                             "ha_pred", "minutes"])
        mm = {p: np.mean([macro[c][m] for m in matches if v4.provider(m) == p] or [np.nan])
              for p in ("metrica", "dfl")}
        L.append("| {} | {:.3f} | {:.3f} | {:.0f} / {:.0f} | {:.1%} | {:.1%} | {:.1f} | {:.1f} |"
                 .format(c, mm["metrica"], mm["dfl"], s["n_pred"], s["n_gt"],
                         s["short_hit"] / max(s["short_n"], 1),
                         s["vshort_hit"] / max(s["vshort_n"], 1), false_rate(rows, c),
                         90 * s["ha_pred"] / s["minutes"]))

    # decisions
    L += ["", "## Paired comparisons and decisions", "",
          "| candidate | reference | mean diff | metrica | dfl | wins | worst match | false "
          "switches | rule |", "|---|---|---|---|---|---|---|---|---|"]
    pairs = [(c, "V3") for c in cands if c != "V3"]
    pairs += [(c, "V4-A") for c in ("V4-B", "V4-C") if c in cands and "V4-A" in cands]
    res = {}
    for c, ref in pairs:
        d = decide(rows, spell, c, ref, matches)
        res[(c, ref)] = d
        failed = [k for k, ok in d["checks"].items() if not ok]
        L.append("| {} | {} | {:+.3f} | {} | {} | {}/{} | {:+.3f} | {:+.0%} | {} |".format(
            c, ref, d["mean"], "{:+.3f}".format(d["prov"]["metrica"]) if "metrica" in d["prov"]
            else "-", "{:+.3f}".format(d["prov"]["dfl"]) if "dfl" in d["prov"] else "-",
            d["wins"], d["n"], d["worst"], d["growth"],
            "**pass**" if d["adopted"] else "fail: " + "; ".join(failed)))

    b_ok = res.get(("V4-B", "V4-A"), {}).get("adopted", False)
    c_ok = res.get(("V4-C", "V4-A"), {}).get("adopted", False)
    eligible = [c for c in cands if c != "V3" and res.get((c, "V3"), {}).get("adopted")]
    if "V4-B" in eligible and not b_ok:
        eligible.remove("V4-B")
    if "V4-C" in eligible and not c_ok:
        eligible.remove("V4-C")
    if "V4-D" in eligible and not (b_ok and c_ok):
        eligible.remove("V4-D")
    choice = "V3"
    if eligible:
        eligible.sort(key=lambda c: COMPLEXITY[c])
        choice = eligible[0]
        for c in eligible[1:]:
            if res[(c, "V3")]["mean"] > res[(choice, "V3")]["mean"] + SIMPLER_MARGIN:
                choice = c
    L += ["", "V4-B and V4-C must also beat V4-A (their only difference) to be credited to their "
          "features; V4-D is only eligible if both do (it shares layer 1 with V4-C, so it was "
          "computed anyway).", "",
          "**Candidate with the best evidence of generalisation: {}**{}".format(
              choice, "" if complete else " (pilot only: not a decision)."), "", SUPERSEDED, ""]
    diag = os.path.join(v4.RES, "touch_diag.json")
    if os.path.isfile(diag):
        with open(diag) as fh:
            dg = json.load(fh)
        L += ["## Touch detector reliability", "",
              "Labels of the external matches are used here only to MEASURE the detector "
              "(team of the touch vs team in possession 0.5 s later), never to detect.", "",
              "| provider | tracking | touches / min | with a team | team agrees with "
              "possession |", "|---|---|---|---|---|"]
        for p in ("metrica", "dfl"):
            for version, sel in (("clean", lambda v: v == "clean"),
                                 ("degraded (eval)", lambda v: v != "clean")):
                z = [r for r in dg if v4.provider(r["match"]) == p and sel(r["version"])]
                if z:
                    L.append("| {} | {} | {:.1f} | {:.0%} | {:.0%} |".format(
                        p, version, np.mean([r["per_min"] for r in z]),
                        np.nanmean([r["assigned"] for r in z]),
                        np.nanmean([r["team_agree"] for r in z])))
        L.append("")
    L += ["## Follow-up", "",
          "Why V4-C makes more false switches, the single correction tested (decoder switch cost "
          "chosen by nested validation) and the candidate fitted on the 10 matches: "
          "[BENCH_V4_FIX.md](BENCH_V4_FIX.md). The table and the decision above are unchanged.",
          ""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(L).rstrip("\n") + "\n")
    print("written", os.path.relpath(path, C.ROOT), "-> choice", choice)
    return choice
